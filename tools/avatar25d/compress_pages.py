"""Derived ASTC 4x4 texture blobs for a baked 2.5D rig (export_rig.py --astc, or standalone on an existing rig folder).

The approved PNG pages are NEVER modified: the blobs are derived artifacts written to <rig>/astc/, each recorded in
<rig>/astc/manifest.json with its own sha256 plus the sha256 of every source PNG it was derived from (a test recomputes both).
Compressed formats cannot be render targets, so the full mip chain (2x2 box filter on premultiplied RGBA8) is baked here.
Blob layout: mip-major, then page (= array layer); every (mip, page) is one block-aligned slab of ceil(w/4)*ceil(h/4)*16 bytes.

On disk each blob is PACKED losslessly (sparse-astc-v1, decoded by apps/mobile/.../renderer/avatar25PackedAstc.ts): the
transparent block that fills 84-89% of a blob is stored once, the other blocks as runs. The manifest's sha256/fileBytes
stay those of the decoded blob (what the GPU receives); `packed` records the file on disk. The files carry the extension
.zip only because it is already a Metro asset extension; the bytes are not a zip archive.

  python compress_pages.py <rig_dir>            # e.g. apps/mobile/src/features/avatar/rigs/girl
  python compress_pages.py --repack <rig_dir>   # pack raw <view>.astc.zip blobs (old exports) without re-encoding
Requires astc-encoder-py==0.1.12 (pinned), numpy, Pillow (not for --repack).
"""
import hashlib
import json
import re
import struct
import sys
from collections import Counter
from importlib import metadata
from pathlib import Path

import numpy as np
from PIL import Image

ENCODER_PIN = '0.1.12'
BLOCK = 4
FORMAT = 'astc-4x4-unorm'
PRESET = 'VERYTHOROUGH'
RAW_EXT = '.astc.zip'
PACKED_EXT = '.astc-packed.zip'
PACKED_ENCODING = 'sparse-astc-v1'
PACKED_MAGIC = b'BSA1'
BLOCK_BYTES = 16
ASSETS_HEADER = '/* Generated by tools/room-avatar-lab/bake25/compress_pages.py (export_rig.py --astc). Do not edit. */'


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def pack_blob(blob: bytes) -> bytes:
    """sparse-astc-v1: the most common 16-byte block once, then (first, count) runs of the others and their bytes."""
    if len(blob) % BLOCK_BYTES:
        raise SystemExit(f'ASTC blob of {len(blob)} bytes is not whole blocks')
    blocks = [blob[i:i + BLOCK_BYTES] for i in range(0, len(blob), BLOCK_BYTES)]
    fill = Counter(blocks).most_common(1)[0][0] if blocks else bytes(BLOCK_BYTES)
    runs, payload, start = [], bytearray(), None
    for index, block in enumerate(blocks + [fill]):
        if block != fill and start is None:
            start = index
        elif block == fill and start is not None:
            runs.append((start, index - start))
            start = None
        if block != fill and index < len(blocks):
            payload += block
    table = b''.join(struct.pack('<II', first, count) for first, count in runs)
    return PACKED_MAGIC + struct.pack('<II', len(blob), len(runs)) + fill + table + bytes(payload)


def unpack_blob(packed: bytes) -> bytes:
    """Inverse of pack_blob (the app's decoder is avatar25PackedAstc.ts); used to prove every pack round-trips."""
    if packed[:4] != PACKED_MAGIC:
        raise SystemExit('not a packed ASTC blob')
    size, run_count = struct.unpack_from('<II', packed, 4)
    fill = packed[12:28]
    out = bytearray(fill * (size // BLOCK_BYTES))
    at = 28 + run_count * 8
    for run in range(run_count):
        first, count = struct.unpack_from('<II', packed, 28 + run * 8)
        out[first * BLOCK_BYTES:(first + count) * BLOCK_BYTES] = packed[at:at + count * BLOCK_BYTES]
        at += count * BLOCK_BYTES
    if at != len(packed):
        raise SystemExit('packed ASTC blob has trailing bytes')
    return bytes(out)


def _write_packed(out_dir: Path, view: str, blob: bytes) -> dict:
    packed = pack_blob(blob)
    if unpack_blob(packed) != blob:
        raise SystemExit(f'{view}: packed blob does not round-trip')
    name = f'{view}{PACKED_EXT}'
    (out_dir / name).write_bytes(packed)
    print(f'{out_dir.parent.name}/{view}: {len(blob) / 1e6:.2f} MB ASTC, {len(packed) / 1e6:.2f} MB packed', flush=True)
    return {'file': name, 'sha256': _sha256(blob), 'fileBytes': len(blob),
            'packed': {'encoding': PACKED_ENCODING, 'bytes': len(packed), 'sha256': _sha256(packed)}}


def _write_assets(out_dir: Path, sets: dict) -> None:
    # header kept from the exporter's old home so re-exports stay byte-identical to the approved files
    lines = [ASSETS_HEADER,
             'export const ROOM_AVATAR_25D_ASTC_MANIFEST = require("./manifest.json") as unknown',
             'export const ROOM_AVATAR_25D_ASTC_FILES: Record<string, number> = {']
    lines += [f'  "{s["file"]}": require("./{s["file"]}"),' for s in sets.values()]
    lines += ['}', '']
    (out_dir / 'astcAssets.ts').write_text('\n'.join(lines))


def _write_manifest(out_dir: Path, manifest: dict) -> None:
    (out_dir / 'manifest.json').write_text(json.dumps(manifest, indent=1, sort_keys=True) + '\n')


def repack_rig(rig_dir: Path) -> dict:
    """Packs raw blobs from an older export in place; the ASTC bytes and their recorded sha256 do not change."""
    out_dir = rig_dir / 'astc'
    manifest = json.loads((out_dir / 'manifest.json').read_text())
    for view, entry in manifest['sets'].items():
        if 'packed' in entry:
            continue
        raw_path = out_dir / entry['file']
        blob = raw_path.read_bytes()
        if _sha256(blob) != entry['sha256'] or len(blob) != entry['fileBytes']:
            raise SystemExit(f'{raw_path} does not match its manifest entry')
        entry.update(_write_packed(out_dir, view, blob))
        raw_path.unlink()
    _write_manifest(out_dir, manifest)
    _write_assets(out_dir, manifest['sets'])
    return manifest


def _premultiplied(path: Path) -> np.ndarray:
    a = np.asarray(Image.open(path).convert('RGBA')).astype(np.float32)
    a[..., :3] = np.round(a[..., :3] * a[..., 3:4] / 255.0)
    return a.astype(np.uint8)


def _mips(a: np.ndarray) -> list:
    out = [a]
    while max(a.shape[:2]) > 1:
        h, w = a.shape[:2]
        nh, nw = max(1, h // 2), max(1, w // 2)
        if h == 1:
            f = a.astype(np.float32)[:, :nw * 2].reshape(1, nw, 2, 4).mean(2)
        elif w == 1:
            f = a.astype(np.float32)[:nh * 2].reshape(nh, 2, 1, 4).mean(1)
        else:
            f = a[:nh * 2, :nw * 2].astype(np.float32).reshape(nh, 2, nw, 2, 4).mean((1, 3))
        a = np.round(f).astype(np.uint8)
        out.append(a)
    return out


def _encode_set(ctx, swizzle, astc, png_paths: list):
    chains = [_mips(_premultiplied(p)) for p in png_paths]
    blob, levels, gpu = bytearray(), [], 0
    for lv in range(len(chains[0])):
        h, w = chains[0][lv].shape[:2]
        bw, bh = -(-w // BLOCK), -(-h // BLOCK)
        for chain in chains:
            padded = np.zeros((bh * BLOCK, bw * BLOCK, 4), np.uint8)
            padded[:h, :w] = chain[lv]
            image = astc.ASTCImage(astc.ASTCType.U8, bw * BLOCK, bh * BLOCK, 1, padded.tobytes())
            blob += bytes(ctx.compress(image, swizzle))
        levels.append({'w': w, 'h': h, 'bw': bw, 'bh': bh})
        gpu += len(chains) * bw * bh * 16
    return bytes(blob), levels, gpu


def compress_rig(rig_dir: Path) -> dict:
    import astc_encoder as astc
    version = metadata.version('astc-encoder-py')
    if version != ENCODER_PIN:
        raise SystemExit(f'astc-encoder-py=={ENCODER_PIN} is pinned for reproducible blobs (found {version})')
    cfg = astc.ASTCConfig(astc.ASTCProfile.LDR, BLOCK, BLOCK, 1, getattr(astc.ASTCQualityPreset, PRESET))
    ctx = astc.ASTCContext(cfg, threads=2)
    swizzle = astc.ASTCSwizzle.from_str('RGBA')
    out_dir = rig_dir / 'astc'
    out_dir.mkdir(exist_ok=True)
    for old in [*out_dir.glob('*' + RAW_EXT), *out_dir.glob('*' + PACKED_EXT)]:
        old.unlink()
    sets = {}
    for view in ('front', 'back'):
        names = sorted((p.name for p in rig_dir.glob(f'{view}_page*.png')), key=lambda n: int(re.search(r'page(\d+)', n).group(1)))
        if not names:
            continue
        paths = [rig_dir / n for n in names]
        sizes = {Image.open(p).size for p in paths}
        if len(sizes) != 1:
            raise SystemExit(f'{view}: pages differ in size {sizes}')
        w, h = sizes.pop()
        if w % BLOCK or h % BLOCK:
            raise SystemExit(f'{view}: {w}x{h} is not a multiple of the {BLOCK}px block (UVs would shift)')
        blob, levels, gpu = _encode_set(ctx, swizzle, astc, paths)
        sets[view] = {
            **_write_packed(out_dir, view, blob), 'gpuBytes': gpu,
            'width': w, 'height': h, 'layers': len(names), 'levels': levels,
            'pages': names, 'sourceSha256': {n: _sha256((rig_dir / n).read_bytes()) for n in names},
        }
    manifest = {'version': 1, 'format': FORMAT, 'block': [BLOCK, BLOCK], 'premultiplied': True, 'preset': PRESET,
                'encoder': {'name': 'astc-encoder-py', 'version': version}, 'sets': sets}
    _write_manifest(out_dir, manifest)
    _write_assets(out_dir, sets)
    return manifest


if __name__ == '__main__':
    if len(sys.argv) == 3 and sys.argv[1] == '--repack':
        repack_rig(Path(sys.argv[2]))
    elif len(sys.argv) == 2:
        compress_rig(Path(sys.argv[1]))
    else:
        raise SystemExit(__doc__)
