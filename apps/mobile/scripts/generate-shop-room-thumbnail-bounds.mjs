#!/usr/bin/env node
// Writes the visible-art box of every room piece's Shop picture (its front view's back layer), so a Shop
// card can centre the drawing itself instead of its transparent canvas. `--check` fails when the file is stale.
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { PNG } from "pngjs"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..")
const FURNITURE_DIR = join(ROOT, "src/features/roomV2/furniture")
const OUTPUT = join(ROOT, "src/features/shop/shopRoomThumbnailBounds.ts")
/** The Shop shows a floor piece's front rotation (r1) and a wall piece's right-wall view. */
const SHOP_LAYERS = ["r1_back", "right_back"]
/** Pixels at or below this alpha are soft edge haze, not drawing. */
const ALPHA_THRESHOLD = 8

export function computeVisibleBounds(png) {
  let minX = png.width, minY = png.height, maxX = -1, maxY = -1
  for (let y = 0; y < png.height; y += 1) {
    for (let x = 0; x < png.width; x += 1) {
      if (png.data[(y * png.width + x) * 4 + 3] <= ALPHA_THRESHOLD) continue
      if (x < minX) minX = x
      if (x > maxX) maxX = x
      if (y < minY) minY = y
      if (y > maxY) maxY = y
    }
  }
  if (maxX < 0) return undefined
  return [png.width, png.height, minX, minY, maxX - minX + 1, maxY - minY + 1]
}

export function renderBoundsModule() {
  const entries = readdirSync(FURNITURE_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort()
    .flatMap((itemId) => SHOP_LAYERS
      .map((layer) => ({ layer, path: join(FURNITURE_DIR, itemId, `${layer}.png`) }))
      .filter(({ path }) => existsSync(path))
      .map(({ layer, path }) => [`${itemId}_layered_${layer}`, computeVisibleBounds(PNG.sync.read(readFileSync(path)))])
      .filter(([, bounds]) => bounds !== undefined))
  const lines = entries.map(([key, bounds]) => `  ${key}: [${bounds.join(", ")}]`)
  return [
    "// Generated by scripts/generate-shop-room-thumbnail-bounds.mjs. Do not edit by hand.",
    "/** Room art key → [canvas width, canvas height, visible x, visible y, visible width, visible height] in px. */",
    "export const SHOP_ROOM_THUMBNAIL_BOUNDS: Readonly<Record<string, readonly number[]>> = {",
    lines.join(",\n"),
    "}",
    ""
  ].join("\n")
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = renderBoundsModule()
  if (process.argv.includes("--check")) {
    const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, "utf8") : ""
    if (current !== next) {
      console.error("shopRoomThumbnailBounds.ts is stale: run node scripts/generate-shop-room-thumbnail-bounds.mjs")
      process.exit(1)
    }
  } else {
    writeFileSync(OUTPUT, next)
  }
}
